import { useState, type ReactNode } from "react";
import { Link } from "react-router-dom";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Bot, Clock3 } from "lucide-react";
import { useTranslation } from "react-i18next";
import type { TFunction } from "i18next";

import { EmptyState } from "@/components/EmptyState";
import { InlineBanner } from "@/components/InlineBanner";
import { PageSkeleton } from "@/components/PageSkeleton";
import { Button } from "@/components/ui/button";
import { ConfigureBuiltInAgentModal } from "@/components/ConfigureBuiltInAgentModal";
import {
  builtInAgentsApi,
  type BuiltInAgentDefinition,
  type BuiltInAgentState,
} from "@/api/builtInAgents";
import { agentsApi } from "@/api/agents";
import { instanceSettingsApi } from "@/api/instanceSettings";
import { queryKeys } from "@/lib/queryKeys";
import { agentUrl } from "@/lib/utils";
import { relativeTime } from "@/lib/utils";

function builtInAgentDisplayName(
  definition: BuiltInAgentDefinition,
  t: TFunction,
): string {
  switch (definition.key) {
    case "briefs":
      return t("builtInAgents.definitions.briefs.displayName", {
        defaultValue: "Briefs Agent",
      });
    case "learning":
      return t("builtInAgents.definitions.learning.displayName", {
        defaultValue: "Learning Agent",
      });
    case "reflection-coach":
      return t("builtInAgents.definitions.reflectionCoach.displayName", {
        defaultValue: "Reflection Coach",
      });
    default:
      return definition.displayName;
  }
}

export interface BuiltInAgentGateProps {
  /** Registry key of the built-in agent that powers this feature (e.g. "briefs"). */
  agentKey: string;
  companyId: string | null | undefined;
  /** Human label for the gated feature. Defaults to the agent's display name. */
  featureLabel?: string;
  children: ReactNode;
}

/**
 * Wraps a feature surface that depends on a built-in agent and renders the
 * right lifecycle state (ux-spec §4):
 *
 * - loading → skeleton
 * - not_provisioned / needs_setup → setup empty-state + configure modal CTA
 * - paused → amber banner + Resume over the (stale) children
 * - ready → children
 */
export function BuiltInAgentGate({
  agentKey,
  companyId,
  featureLabel,
  children,
}: BuiltInAgentGateProps) {
  const { t } = useTranslation();
  const queryClient = useQueryClient();
  const [configureOpen, setConfigureOpen] = useState(false);

  const experimentalQuery = useQuery({
    queryKey: queryKeys.instance.experimentalSettings,
    queryFn: () => instanceSettingsApi.getExperimental(),
  });
  const builtInAgentsEnabled = experimentalQuery.data?.enableBuiltInAgents === true;
  const { data: states, isLoading: statesLoading } = useQuery({
    queryKey: queryKeys.builtInAgents.list(companyId ?? "__none__"),
    queryFn: () => builtInAgentsApi.list(companyId!),
    enabled: Boolean(companyId && builtInAgentsEnabled),
  });

  const state: BuiltInAgentState | undefined = states?.find(
    (entry) => entry.definition.key === agentKey,
  );

  const resume = useMutation({
    mutationFn: (agentId: string) =>
      agentsApi.resume(agentId, companyId ?? undefined),
    onSuccess: () => {
      queryClient.invalidateQueries({
        queryKey: queryKeys.builtInAgents.list(companyId ?? "__none__"),
      });
      if (companyId)
        queryClient.invalidateQueries({
          queryKey: queryKeys.agents.list(companyId),
        });
    },
  });

  // Unknown key or still resolving the company — fail open to the feature.
  if (!companyId) return <>{children}</>;
  if ((experimentalQuery.isLoading || statesLoading) && !states) return <PageSkeleton variant="detail" />;
  if (!state) return <>{children}</>;

  const displayName = builtInAgentDisplayName(state.definition, t);
  const label = featureLabel ?? displayName;

  if (state.status === "not_provisioned" || state.status === "needs_setup") {
    return (
      <>
        <EmptyState
          icon={Bot}
          title={t("builtInAgents.gate.setupTitle", {
            defaultValue: "Set up the {{name}}",
            name: displayName,
          })}
          message={t("builtInAgents.gate.setupMessage", {
            defaultValue:
              "{{feature}} is generated by a built-in agent. Configure its model to enable the feature.",
            feature: label,
          })}
          action={t("builtInAgents.gate.setupAction", {
            defaultValue: "Set up {{name}}",
            name: displayName,
          })}
          onAction={() => setConfigureOpen(true)}
          hideActionIcon
        />
        <ConfigureBuiltInAgentModal
          companyId={companyId}
          state={state}
          open={configureOpen}
          onOpenChange={setConfigureOpen}
        />
      </>
    );
  }

  if (state.status === "pending_approval") {
    return (
      <EmptyState
        icon={Clock3}
        title={t("builtInAgents.gate.pendingApprovalTitle", {
          defaultValue: "{{name}} is pending approval",
          name: displayName,
        })}
        message={t("builtInAgents.gate.pendingApprovalMessage", {
          defaultValue:
            "{{feature}} will be available after the board approves this built-in agent hire.",
          feature: label,
        })}
      />
    );
  }

  if (state.status === "paused" && state.agent) {
    const pausedAt = state.agent.pausedAt
      ? relativeTime(state.agent.pausedAt)
      : null;
    return (
      <div className="space-y-4">
        <InlineBanner
          tone="warning"
          title={t("builtInAgents.gate.pausedTitle", {
            defaultValue: "{{feature}} is paused.",
            feature: label,
          })}
          actions={
            <>
              <Button variant="ghost" size="sm" asChild>
                <Link to={agentUrl(state.agent)}>
                  {t("builtInAgents.gate.viewAgent", {
                    defaultValue: "View agent",
                  })}
                </Link>
              </Button>
              <Button
                size="sm"
                onClick={() => state.agent && resume.mutate(state.agent.id)}
                disabled={resume.isPending}
              >
                {resume.isPending
                  ? t("builtInAgents.gate.resuming", {
                      defaultValue: "Resuming…",
                    })
                  : t("builtInAgents.gate.resumeAgent", {
                      defaultValue: "Resume agent",
                    })}
              </Button>
            </>
          }
        >
          {pausedAt
            ? t("builtInAgents.gate.pausedMessageWithTime", {
                defaultValue:
                  "Its built-in agent was paused {{pausedAt}}, so new {{feature}} content isn't being generated.",
                pausedAt,
                feature: label,
              })
            : t("builtInAgents.gate.pausedMessage", {
                defaultValue:
                  "Its built-in agent was paused, so new {{feature}} content isn't being generated.",
                feature: label,
              })}
        </InlineBanner>
        {/* Paused ≠ hidden: keep existing content readable, marked stale. */}
        <div className="opacity-70">{children}</div>
      </div>
    );
  }

  return <>{children}</>;
}
